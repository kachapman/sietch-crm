"""Pure mapping layer: Sietch document_templates row + request payload -> builder inputs.

Ported/derived from kachapman/sherwood-toolbox @ 3d5bf83
(toolbox/tools/documents/branding.py + toolbox/tools/documents/routes.py).
Sherwood builds its `brand` dict from a per-customer branding profile and
its `job` dict from a CRM fetch; Sietch builds the same shapes from the
`document_templates` table plus the JSON payload posted by the invoice/COC
modal.

Everything here is a pure function: no DB, no filesystem writes, no HTTP.
The only filesystem touch is *resolving* (not reading) a repo-relative asset
path, which is a pure string operation.

Field mapping (Sietch source -> builder key)
---------------------------------------------
brand:
  name          <- template.company_name
  address       <- template.company_address
  city_state_zip<- template.company_city_state_zip
  phone         <- template.company_phone
  email         <- template.company_email
  accent        <- template.primary_color
  logo_path     <- template.logo_path
  invoice_title <- template.invoice_title
  coc_title     <- template.coc_title
  footer_text   <- "Generated by Sietch CRM" when template.show_branding_footer else ""
  website       <- template.company_website
  license       <- template.company_license (through license_label())

job:
  customer_name   <- payload.customer_name
  street          <- payload.street
  city_state_zip  <- payload.city_state_zip
  job_number      <- payload.project_number
  insurance_claim <- payload.claim_number
  sales_rep       <- payload.sales_rep
  invoice_number  <- payload.invoice_number
  invoice_date    <- payload.invoice_date
  terms           <- payload.terms
  invoice_notes   <- payload.notes
  completion_date <- payload.completion_date
  note            <- payload.note

items: payload.base_amount + payload.line_items -> list of (description, amount)

opts (COC):
  statement       <- Sietch classic COC wording (see COC_STATEMENT)
  signature_path  <- template.signature_path (only when include_signature)
  signer_name     <- payload.signature_name
  signer_title    <- template.signature_title
  signatures      <- template.show_signature_lines (default True)
"""

# The Sietch classic (fpdf2) COC had no centred statement paragraph; the
# closest equivalent wording it used for the free-text note is below. It is
# reused verbatim as the modern COC statement so the certificate reads the
# same as before (see docs/features/2026-11-03-invoice-coc-upgrade.md).
COC_STATEMENT = "Work completed per agreement."

BRANDING_FOOTER_TEXT = "Generated by Sietch CRM"

# The label the base charge is printed under on an invoice. It used to be the
# payment TERMS ("Due on receipt"), which reads like a payment condition
# rather than a charge description.
BASE_CHARGE_LABEL = "Base charge"

# ── Certificate title (v28.2) ──────────────────────────────────────────────
# This lives here, NOT in doc_pdf.pdf_common, because pdf_common imports
# reportlab at module load. The classic fpdf2 renderers are the fallback
# when reportlab is missing, so anything they need must live in a module
# that does not pull reportlab in. doc_pdf.pdf_common re-exports it for
# the modern builders.
COC_TITLE = "Certificate of Completion"
_SMALL_WORDS = {"a", "an", "and", "as", "at", "by", "for", "in", "of", "on", "or", "the", "to"}


def coc_title(raw):
    """Certificate title as printed (v28.2, Ken: lowercase "of").

    Blank, or any casing of "Certificate of Completion" (the shipped
    companies.json and older saved companies had "CERTIFICATE OF COMPLETION"),
    gives "Certificate of Completion". Another all-caps title is title-cased
    with short words like "of" kept lowercase; mixed-case titles are left as
    typed."""
    t = " ".join((raw or "").split())
    if not t or t.lower() == COC_TITLE.lower():
        return COC_TITLE
    if t.isupper():
        words = t.lower().split(" ")
        return " ".join(w if (i and w in _SMALL_WORDS) else w[:1].upper() + w[1:]
                        for i, w in enumerate(words))
    return t


def license_label(value) -> str:
    """The license as printed.

    Upstream prefixes "License " unless the value already starts with "lic"
    or "#". Sietch (2026-11-03): do NOT prefix when the value already
    contains "lic" anywhere (case-insensitive) or starts with "#" -- so
    "OH LIC 104.8872" prints as-is instead of "License OH LIC 104.8872".
    """
    text = _s(value)
    if not text:
        return ""
    low = text.lower()
    if "lic" in low or text.startswith("#"):
        return text
    return "License " + text


def _s(value) -> str:
    """Coerce to a stripped string ('' for None)."""
    if value is None:
        return ""
    return str(value).strip()


def _money(value) -> float:
    """Coerce a user-entered amount string to float; returns 0 on failure.

    Mirrors server.py `_money` so the classic and modern renderers agree.
    """
    if value is None:
        return 0.0
    try:
        return float(str(value).replace(",", "").replace("$", "").strip() or 0)
    except (TypeError, ValueError):
        try:
            return float(value)
        except Exception:
            return 0.0


def _resolve_asset_path(path, root=None):
    """Resolve a template-relative asset path against ROOT.

    Returns an absolute path string when the file exists, otherwise None.
    A missing file must never crash generation -- the builders already skip
    unreadable images, but returning None keeps the mapping honest.

    `root` may be a str or pathlib.Path. When omitted, the server's ROOT is
    used (imported lazily so this module stays importable without server.py).
    """
    if not path:
        return None
    import pathlib
    if root is None:
        try:
            from server import ROOT  # local import: keeps this module importable standalone
            root = ROOT
        except Exception:
            return None
    try:
        p = pathlib.Path(str(path))
        if not p.is_absolute():
            p = pathlib.Path(root) / p
        if p.exists():
            return str(p)
    except Exception:
        pass
    return None


def build_brand(template, root=None):
    """document_templates row -> brand dict for the modern builders."""
    template = template or {}
    logo = _resolve_asset_path(template.get("logo_path"), root=root)
    footer = BRANDING_FOOTER_TEXT if template.get("show_branding_footer", True) else ""
    return {
        "name": _s(template.get("company_name")),
        "address": _s(template.get("company_address")),
        "city_state_zip": _s(template.get("company_city_state_zip")),
        "phone": _s(template.get("company_phone")),
        "email": _s(template.get("company_email")),
        "accent": _s(template.get("primary_color")) or "",
        "logo_path": logo,
        "footer_text": footer,
        "invoice_title": _s(template.get("invoice_title")) or "INVOICE",
        "coc_title": _s(template.get("coc_title")) or "Certificate of Completion",
        # Optional branding extras (migration 045). Empty -> omitted from the
        # rendered document, never printed as a blank label.
        "website": _s(template.get("company_website")),
        "license": license_label(template.get("company_license")),
    }


def build_job(payload, today=None):
    """Request payload -> job dict for the modern builders."""
    payload = payload or {}
    today = _s(today)
    return {
        "customer_name": _s(payload.get("customer_name")),
        "street": _s(payload.get("street")),
        "city_state_zip": _s(payload.get("city_state_zip")),
        "job_number": _s(payload.get("project_number")),
        "insurance_claim": _s(payload.get("claim_number")),
        "sales_rep": _s(payload.get("sales_rep")),
        "invoice_number": _s(payload.get("invoice_number")),
        "invoice_date": _s(payload.get("invoice_date")),
        "terms": _s(payload.get("terms")),
        "invoice_notes": _s(payload.get("notes")),
        "completion_date": _s(payload.get("completion_date")) or today,
        "note": _s(payload.get("note")),
    }


def build_items(payload, line_items=None):
    """base_amount + line_items -> list of (description, amount).

    The classic Sietch invoice rendered `base_amount` as the FIRST table row
    and only rendered it when it was greater than zero. When there was no
    base amount but a claim number existed, it rendered a text-only first row
    "Insurance Claim # <claim>".

    The modern builder has no separate base-charge concept, so the base
    amount is folded in as the first line item, so the totals and the reading
    order match.

    **The base charge's description** used to be the payment TERMS
    ("Due on receipt"), which reads like a payment condition rather than a
    charge description. As of 2026-11-03 it is `BASE_CHARGE_LABEL`
    ("Base charge"); a payload may override it with `base_description`.

    **$0.00 rows are hidden** (Sietch decision, 2026-11-03): a line whose
    amount is exactly 0.00 is not printed, in either layout. The amount
    contributes nothing to the total either way, so the grand total is
    unchanged -- only the row itself disappears.

    `line_items` overrides payload["line_items"] when given (the caller
    already resolved template defaults vs. payload).
    """
    payload = payload or {}
    items = []
    base_amount = _money(payload.get("base_amount"))
    if base_amount > 0:
        desc = _s(payload.get("base_description")) or BASE_CHARGE_LABEL
        items.append((desc, base_amount))
    if line_items is None:
        line_items = payload.get("line_items")
    for li in (line_items or []):
        if not isinstance(li, dict):
            continue
        desc = _s(li.get("description"))
        amt = _money(li.get("amount"))
        # Hidden: an empty description with no amount, and any $0.00 row.
        if not desc and amt == 0:
            continue
        if amt == 0:
            continue
        items.append((desc, amt))
    return items


def build_invoice_signature(payload, template, root=None):
    """Signature block for the modern invoice, or None.

    Mirrors the classic renderer: a block is only drawn when signatures are
    included AND a signature image is configured on the template. The name
    line and date are printed even when the image file is missing, so the
    signer still appears on the document.
    """
    payload = payload or {}
    template = template or {}
    include = payload.get("include_signature")
    if include is None:
        include = template.get("show_signature", True)
    if not include:
        return None
    name = _s(payload.get("signature_name")) or _s(template.get("signature_name")) or _s(payload.get("sales_rep"))
    title = _s(template.get("signature_title"))
    date_text = _s(payload.get("invoice_date"))
    sig_path = _resolve_asset_path(template.get("signature_path"), root=root)
    if not name and not title and not date_text and not sig_path:
        return None
    return {"path": sig_path, "name": name, "title": title, "date": date_text}


def build_coc_opts(payload, template, root=None):
    """Request payload + template -> opts dict for build_coc."""
    payload = payload or {}
    template = template or {}
    include = payload.get("include_signature")
    if include is None:
        include = template.get("show_signature", True)
    sig_path = _resolve_asset_path(template.get("signature_path"), root=root)
    if not include:
        sig_path = None
    # v28.2: the template's "Include signature lines" switch. Off leaves the
    # whole SIGNATURES section out of the certificate (heading included).
    # The payload may override it per request.
    show_lines = payload.get("include_signature_lines")
    if show_lines is None:
        show_lines = template.get("show_signature_lines", True)
    return {
        "statement": COC_STATEMENT,
        "signature_path": sig_path,
        "signer_name": _s(payload.get("signature_name")) or _s(template.get("signature_name")) or _s(payload.get("sales_rep")),
        "signer_title": _s(template.get("signature_title")),
        "signatures": bool(show_lines),
        # There is no `homeowner_line` option: Ken's decision (2026-11-03) is
        # that the Sietch COC never draws a property-owner signature line, so
        # the builder no longer has that branch.
    }


