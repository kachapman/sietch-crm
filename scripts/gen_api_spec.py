#!/usr/bin/env python3
"""Regenerate api_spec_routes.py from server.py's dispatch code.

    python3 scripts/gen_api_spec.py --write

`api_spec_routes.py` is committed so the spec is a reviewable artifact;
tests/test_openapi.py fails when server.py gains a route that is not in it.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from extract_api_routes import extract_routes  # noqa: E402

OUT = ROOT / "api_spec_routes.py"

TAG_OVERRIDES = {
    "history-categories": "history",
    "history-attachments": "history",
    "service-feeds": "service-feeds",
    "task-labels": "tasks",
    "custom-field": "reference",
    "openapi": "meta",
}

VERBS = {
    "GET": "Get",
    "POST": "Create",
    "PUT": "Update",
    "PATCH": "Patch",
    "DELETE": "Delete",
}


def tag_for(path: str) -> str:
    parts = [p for p in path.strip("/").split("/") if p]
    # /api/v2/<tag>/...
    raw = parts[2] if len(parts) > 2 else "misc"
    return TAG_OVERRIDES.get(raw, raw)


def summary_for(method: str, path: str, params: list[str]) -> str:
    parts = [p for p in path.strip("/").split("/") if p]
    noun = parts[-1] if parts else "resource"
    if noun.startswith("{"):
        noun = parts[-2] if len(parts) > 1 else "resource"
    if noun in ("reorder", "count", "status", "search", "export", "import"):
        return f"{VERBS.get(method, method)} {path.split('/api/v2/')[-1]}"
    singular = noun[:-1] if noun.endswith("s") and len(noun) > 3 else noun
    readable = singular.replace("-", " ").replace("_", " ")
    if params and method == "GET":
        return f"Get one {readable}"
    if method == "GET":
        return f"List {readable}"
    return f"{VERBS.get(method, method)} {readable}"


def render(routes: list[dict]) -> str:
    lines = [
        '"""Generated by scripts/gen_api_spec.py — do not edit by hand.',
        "",
        "Every /api/v2 route found in server.py's dispatch code. tests/test_openapi.py",
        "fails when this table and the dispatcher disagree.",
        '"""',
        "",
        "ROUTES = [",
    ]
    for r in routes:
        lines.append(
            "    {\"method\": %r, \"path\": %r, \"params\": %r, \"tag\": %r, \"summary\": %r},"
            % (r["method"], r["path"], r["params"], tag_for(r["path"]),
               summary_for(r["method"], r["path"], r["params"]))
        )
    lines.append("]")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    routes = [r for r in extract_routes() if r["source"] != "startswith"]
    text = render(routes)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT} ({len(routes)} routes)")
    else:
        print(text[:2000])
        print(f"... {len(routes)} routes (pass --write)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
